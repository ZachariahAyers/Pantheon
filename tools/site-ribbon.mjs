// Writes the browser desk's ribbon from the add-in's own: src/Pantheon.Browser/wwwroot/ribbon.js from
// the buttons PantheonRibbon.vb builds, and wwwroot/icons/ from the icons those buttons load (copied,
// never altered). `node tools/site-ribbon.mjs --check` fails when either is stale or holds a file the
// ribbon no longer names.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, unlinkSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const ribbonSource = new URL("src/Pantheon.AutoCAD/Ui/PantheonRibbon.vb", root);
const iconSource = new URL("src/Pantheon.AutoCAD/Icons/", root);
const out = new URL("src/Pantheon.Browser/wwwroot/", root);

const BUTTON =
  /MakeButton\("([^"]+)", "([^"]+)", "([^"]+)", "([^"]+)"(, png:=True)?\)|MakeTextButton\("([^"]+)", "([^"]+)", "([^"]+)"\)/g;

/** The panels and buttons in ribbon order, and the icon files they load. */
export function build() {
  const text = readFileSync(ribbonSource, "utf8");
  const chunks = text.split('MakePanel("').slice(1);
  const icons = new Set();
  const panels = chunks.map((chunk) => {
    const title = chunk.slice(0, chunk.indexOf('"'));
    const buttons = [...chunk.matchAll(BUTTON)].map((m) => {
      if (m[6]) return { label: m[6], description: m[7], command: m[8].trim(), small: null, large: null };
      const [small, large] = m[5] ? [`${m[3]}.png`, `${m[3]}.png`] : [`${m[3]}_S.bmp`, `${m[3]}_L.bmp`];
      icons.add(small);
      icons.add(large);
      return { label: m[1], description: m[2], command: m[4].trim(), small: `icons/${small}`, large: `icons/${large}` };
    });
    return { title, buttons };
  });
  const script =
    "// Generated by tools/site-ribbon.mjs from PantheonRibbon.vb; do not edit.\n" +
    `export const panels = ${JSON.stringify(panels, null, 2)};\n`;
  const files = new Map([["ribbon.js", Buffer.from(script)]]);
  for (const icon of icons) files.set(`icons/${icon}`, readFileSync(new URL(icon, iconSource)));
  return files;
}

/** Names of files that differ from what build() writes, or that it would remove. */
export function stale(files = build()) {
  const iconsDir = new URL("icons/", out);
  const present = existsSync(iconsDir) ? readdirSync(iconsDir).map((name) => `icons/${name}`) : [];
  const wrong = [...files].filter(([name, body]) => {
    const target = new URL(name, out);
    return !existsSync(target) || !readFileSync(target).equals(body);
  });
  return [...wrong.map(([name]) => name), ...present.filter((name) => !files.has(name))];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = build();
  if (process.argv.includes("--check")) {
    const names = stale(files);
    if (names.length > 0) {
      console.error(`wwwroot ribbon is stale (run node tools/site-ribbon.mjs): ${names.join(", ")}`);
      process.exit(1);
    }
  } else {
    mkdirSync(new URL("icons/", out), { recursive: true });
    for (const name of stale(files)) if (!files.has(name)) unlinkSync(new URL(name, out));
    for (const [name, body] of files) writeFileSync(new URL(name, out), body);
  }
}
